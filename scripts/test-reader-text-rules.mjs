import assert from "node:assert/strict";
import { readFile } from "node:fs/promises";
import ts from "typescript";

const source = await readFile(new URL("../src/features/reader/textReplacements.ts", import.meta.url), "utf8");
const { outputText } = ts.transpileModule(source, { compilerOptions: { module: ts.ModuleKind.ESNext } });
const { applyTextRules } = await import(`data:text/javascript;base64,${Buffer.from(outputText).toString("base64")}`);
const original = "　　清风清风\n　　广告123\n<b>原文</b>";
const rule = overrides => ({ id: "r", name: "", enabled: true, scope: "all", isRegex: false, pattern: "清风", replacement: "明月", ...overrides });
assert.equal(applyTextRules(original, []), original);
assert.equal(applyTextRules(original, [rule({})]), original.replaceAll("清风", "明月"));
assert.equal(applyTextRules(original, [rule({ enabled: false })]), original);
assert.equal(applyTextRules(original, [rule({ scope: "book:other" })], "current"), original);
assert.equal(applyTextRules(original, [rule({ scope: "book:current" })], "current"), original.replaceAll("清风", "明月"));
assert.equal(applyTextRules(original, [rule({ isRegex: true, pattern: "广告\\d+\\n", replacement: "" })]), "　　清风清风\n　　<b>原文</b>");
assert.equal(applyTextRules(original, [rule({ isRegex: true, pattern: "[" })]), original);
assert.equal(applyTextRules("abc abc", [rule({ isRegex: true, pattern: "abc", replacement: "@js:result.toUpperCase()" })]), "ABC ABC");
assert.equal(applyTextRules(original, [rule({}), rule({ pattern: "明月", replacement: "山川" })]), original.replaceAll("清风", "山川"));
assert.equal(applyTextRules(original, []), original, "Removing rules must restore the original cached text");
console.log("Reader text rules passed: literal/regex, scope, disabled rules, invalid regex, script replacement, ordering and original text preservation.");
